import { describe, it, expect } from "vitest";
import {
  是草稿单号,
  生成保养单号,
  找重复项目名,
  计算需求顺延,
  保养单草稿前缀,
} from "./maintenance";

describe("是草稿单号", () => {
  it("DRAFT- 开头的是草稿", () => {
    expect(是草稿单号("DRAFT-1721520000000")).toBe(true);
  });

  it("正式保养单号不是草稿", () => {
    expect(是草稿单号("BY-20260722-001")).toBe(false);
  });

  it("普通工单号不是草稿", () => {
    expect(是草稿单号("WO-20260722-001")).toBe(false);
  });

  it("空字符串不是草稿", () => {
    expect(是草稿单号("")).toBe(false);
  });

  it("草稿前缀常量本身是 DRAFT-", () => {
    expect(保养单草稿前缀).toBe("DRAFT-");
  });
});

describe("生成保养单号", () => {
  it("当天第一单序号为 001", () => {
    expect(生成保养单号("20260722", 0)).toBe("BY-20260722-001");
  });

  it("序号按已有数量+1，不足3位补零", () => {
    expect(生成保养单号("20260722", 8)).toBe("BY-20260722-009");
  });

  it("超过99单时序号为3位", () => {
    expect(生成保养单号("20260722", 99)).toBe("BY-20260722-100");
  });

  it("日期原样拼接", () => {
    expect(生成保养单号("20260101", 0)).toBe("BY-20260101-001");
  });
});

describe("找重复项目名", () => {
  it("找出重复的单个项目", () => {
    expect(找重复项目名(["换机油", "换机滤"], ["换机油", "刹车片"])).toEqual(["换机油"]);
  });

  it("找出多个重复项目，保持待导入顺序", () => {
    expect(找重复项目名(["换机油", "刹车片"], ["刹车片", "换机油", "四轮定位"])).toEqual([
      "刹车片",
      "换机油",
    ]);
  });

  it("无重复返回空数组", () => {
    expect(找重复项目名(["换机油"], ["刹车片"])).toEqual([]);
  });

  it("待导入为空返回空数组", () => {
    expect(找重复项目名(["换机油"], [])).toEqual([]);
  });

  it("已有为空返回空数组", () => {
    expect(找重复项目名([], ["换机油"])).toEqual([]);
  });
});

describe("计算需求顺延", () => {
  it("每个 seq +1", () => {
    expect(计算需求顺延([1, 2, 3])).toEqual([2, 3, 4]);
  });

  it("空列表返回空数组", () => {
    expect(计算需求顺延([])).toEqual([]);
  });

  it("单个需求顺延", () => {
    expect(计算需求顺延([5])).toEqual([6]);
  });
});
