const 最大词长 = 8;

/**
 * 对输入文本进行中文/英文混合分词
 * @param text 用户输入的搜索关键词
 * @param customWords 自定义扩展词库（可选），会与默认词库合并
 * @returns 分词结果数组
 */
export function 中文分词(text: string, customWords: string[] = []): string[] {
  const 合并词库 = new Set(默认词库);
  for (const w of customWords) {
    if (w.trim().length > 0) {
      合并词库.add(w.trim());
    }
  }

  const 结果: string[] = [];
  let i = 0;
  const 长度 = text.length;

  while (i < 长度) {
    const 字符 = text[i];

    /* 跳过空白 */
    if (/\s/.test(字符)) {
      i++;
      continue;
    }

    /* 英文/数字连续字符 */
    if (/[a-zA-Z0-9]/.test(字符)) {
      let j = i;
      while (j < 长度 && /[a-zA-Z0-9]/.test(text[j])) {
        j++;
      }
      const 词 = text.slice(i, j);
      if (词.length > 0) {
        结果.push(词);
      }
      i = j;
      continue;
    }

    /* 中文正向最大匹配 */
    let 已匹配 = false;
    for (let l = Math.min(最大词长, 长度 - i); l >= 1; l--) {
      const 候选词 = text.slice(i, i + l);
      if (合并词库.has(候选词)) {
        结果.push(候选词);
        i += l;
        已匹配 = true;
        break;
      }
    }

    if (!已匹配) {
      /* 非中文、非英文数字的字符直接跳过 */
      if (/[一-龥]/.test(字符)) {
        结果.push(字符);
      }
      i++;
    }
  }

  return 结果.filter((w) => w.trim().length > 0);
}

/**
 * 扩展词库，用于业务新增术语
 * @param words 要添加的词数组
 */
export function 扩展词库(words: string[]): void {
  for (const w of words) {
    if (w.trim().length > 0) {
      默认词库.add(w.trim());
    }
  }
}
