import { describe, it, expect } from "vitest";
import { 计算施工中断秒数, 格式化时长, 格式化计时器, type 施工日志行 } from "./constructionTime";

const 此刻 = new Date("2026-08-03T12:00:00Z");
function 日志(action: string, 时间: string): 施工日志行 {
  return { action, created_at: `2026-08-03T${时间}:00Z` };
}

describe("计算施工中断秒数", () => {
  it("单段施工未结束：算到此刻", () => {
    const r = 计算施工中断秒数([日志("start", "10:00")], 此刻);
    expect(r).toEqual({ 施工秒: 7200, 中断秒: 0 });
  });

  it("施工→中断→恢复：施工两段、中断一段", () => {
    const r = 计算施工中断秒数(
      [日志("start", "10:00"), 日志("pause", "10:10"), 日志("resume", "10:20")],
      此刻
    );
    expect(r).toEqual({ 施工秒: 600 + 6000, 中断秒: 600 });
  });

  it("已完工：完整配对，不算到此刻", () => {
    const r = 计算施工中断秒数(
      [日志("start", "09:00"), 日志("pause", "09:30"), 日志("resume", "10:00"), 日志("complete", "11:00")],
      此刻
    );
    expect(r).toEqual({ 施工秒: 1800 + 3600, 中断秒: 1800 });
  });

  it("多次中断累计", () => {
    const r = 计算施工中断秒数(
      [
        日志("start", "08:00"), 日志("pause", "08:30"), 日志("resume", "09:00"),
        日志("pause", "10:00"), 日志("resume", "10:30"),
      ],
      此刻
    );
    expect(r).toEqual({ 施工秒: 1800 + 3600 + 5400, 中断秒: 1800 + 1800 });
  });

  it("正在中断中：中断段算到此刻", () => {
    const r = 计算施工中断秒数(
      [日志("start", "10:00"), 日志("pause", "11:00")],
      此刻
    );
    expect(r).toEqual({ 施工秒: 3600, 中断秒: 3600 });
  });

  it("异常数据：连续两个 start，前一段丢弃（同 RPC）", () => {
    const r = 计算施工中断秒数(
      [日志("start", "09:00"), 日志("start", "10:00"), 日志("pause", "10:30")],
      此刻
    );
    expect(r).toEqual({ 施工秒: 1800, 中断秒: 5400 });
  });

  it("空日志 → 全 0；乱序输入自动排序", () => {
    expect(计算施工中断秒数([], 此刻)).toEqual({ 施工秒: 0, 中断秒: 0 });
    const r = 计算施工中断秒数(
      [日志("pause", "10:10"), 日志("start", "10:00"), 日志("resume", "10:20")],
      此刻
    );
    expect(r.施工秒).toBe(600 + 6000);
    expect(r.中断秒).toBe(600);
  });
});

describe("格式化时长", () => {
  it("各档格式", () => {
    expect(格式化时长(30)).toBe("不足1分钟");
    expect(格式化时长(600)).toBe("10分");
    expect(格式化时长(3600)).toBe("1小时");
    expect(格式化时长(5400)).toBe("1小时30分");
    expect(格式化时长(90000)).toBe("1天1小时");
    expect(格式化时长(172800)).toBe("2天");
  });
});

describe("格式化计时器", () => {
  it("HH:MM:SS 计时器样式", () => {
    expect(格式化计时器(0)).toBe("00:00:00");
    expect(格式化计时器(30)).toBe("00:00:30");
    expect(格式化计时器(600)).toBe("00:10:00");
    expect(格式化计时器(5025)).toBe("01:23:45");
    expect(格式化计时器(36000)).toBe("10:00:00");
  });

  it("超过 1 天加天数前缀", () => {
    expect(格式化计时器(90000)).toBe("1天 01:00:00");
    expect(格式化计时器(183845)).toBe("2天 03:04:05");
  });

  it("负数和小数容错", () => {
    expect(格式化计时器(-5)).toBe("00:00:00");
    expect(格式化计时器(61.9)).toBe("00:01:01");
  });
});
